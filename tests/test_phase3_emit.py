"""Phase 3 unit tests: C emission determinism + golden lowering fragments.

The fragments below pin the exact lowering the LiteSVM acceptance suite
(``tests/test_phase3_litesvm.py``) proved end-to-end: role checks, PDA
verification, the System create_account CPI (with the account scan), the
stored account discriminator, ``require`` → 6000 and checked arithmetic →
1009, with true source line numbers. If an emitter change turns these red,
update both this file *and* re-run the LiteSVM suite before committing.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from pythsol.compiler.pipeline import GeneratedProgram, emit_program

COUNTER_PATH = Path(__file__).parents[1] / "examples" / "counter" / "programs" / "counter.py"
COUNTER_SOURCE = COUNTER_PATH.read_text(encoding="utf-8")


@pytest.fixture(scope="module")
def generated() -> GeneratedProgram:
    gen = emit_program(COUNTER_SOURCE, COUNTER_PATH)
    assert gen.ok, "\n".join(diag.render() for diag in gen.diagnostics)
    return gen


# Byte-for-byte stability is a build-acceptance prerequisite (TRD §18 Phase 3:
# two consecutive builds of the same source must produce identical .so files).
def test_emit_is_deterministic_across_calls() -> None:
    first = emit_program(COUNTER_SOURCE, COUNTER_PATH)
    second = emit_program(COUNTER_SOURCE, COUNTER_PATH)
    assert first.ok and second.ok
    assert first.c_text == second.c_text


def test_emit_is_independent_of_the_source_directory(tmp_path: Path) -> None:
    """Same bytes at a different absolute path must produce identical C."""
    moved = tmp_path / "counter.py"
    moved.write_text(COUNTER_SOURCE, encoding="utf-8", newline="\n")
    gen_local = emit_program(COUNTER_SOURCE, moved)
    gen_shared = emit_program(COUNTER_SOURCE, COUNTER_PATH)
    assert gen_local.ok and gen_shared.ok
    assert gen_local.c_text == gen_shared.c_text


