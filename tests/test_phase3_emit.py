def test_generated_c_matches_golden_lowering(generated: GeneratedProgram) -> None:
    """Pin every proven lowering decision of the phase 3 emitter."""
    missing = [fragment for fragment in _GOLDEN_FRAGMENTS if fragment not in generated.c_text]
    assert missing == [], f"{len(missing)} golden fragments are missing:\n" + "\n".join(
        f"  - {fragment}" for fragment in missing
    )


def test_increment_handler_lowers_without_init_logic(
    generated: GeneratedProgram,
) -> None:
    """The increment handler must be PDA-free and CPI-free."""
    start = generated.c_text.index("static uint64_t pyf_increment")
    end = generated.c_text.index("static const RtDispatchEntry")
    increment_body = generated.c_text[start:end]
    assert "rt_system_create_account" not in increment_body
    assert "rt_verify_pda" not in increment_body
    assert "rt_st_disc" not in increment_body
    # ...but keeps the mutating role check + checked arithmetic.
    assert "writable required: counter" in increment_body
    assert "rt_checked_add_u64" in increment_body
    assert '1009u, "counter.py", 52u' in increment_body
